package bundle

import (
	"encoding/json"
	"fmt"
	"regexp"
	"strconv"
	"strings"

	"scene-palette/internal/colorx"
	"scene-palette/internal/palette"
)

var hexColor = regexp.MustCompile(`^#[0-9a-fA-F]{6}$`)
var tokenSlug = regexp.MustCompile(`[^a-z0-9]+`)

type exportToken struct {
	palette.Token
	Key string
	RGB colorx.RGB
}

func tokens(document palette.Document) ([]exportToken, error) {
	all := append(append([]palette.Token{}, document.Core...), document.Found...)
	result := make([]exportToken, 0, len(all))
	for index, token := range all {
		if !hexColor.MatchString(token.Hex) {
			return nil, fmt.Errorf("bundle token %d has invalid hex %q", index+1, token.Hex)
		}
		key := token.Role()
		if index >= len(document.Core) {
			key = fmt.Sprintf("found_%d", index-len(document.Core)+1)
		}
		value, _ := strconv.ParseUint(token.Hex[1:], 16, 24)
		result = append(result, exportToken{Token: token, Key: key, RGB: colorx.RGB{R: int(value >> 16), G: int(value >> 8 & 255), B: int(value & 255)}})
	}
	return result, nil
}

// Format renders the same role keys and colors as the browser exports. Review
// eligibility is independently verified; imported claims are never trusted.
func Format(data []byte, format string) (string, error) {
	document, err := palette.Parse(data)
	if err != nil {
		return "", err
	}
	tk, err := tokens(document)
	if err != nil {
		return "", err
	}
	verified, err := document.VerifyReview()
	if err != nil {
		return "", err
	}
	name, review := safeComment(document.Name), reviewLabel(document, verified)
	var out strings.Builder
	switch format {
	case "css":
		fmt.Fprintf(&out, "/* %s — Scene Palette */\n/* Review: %s */\n:root {\n", name, review)
		for _, token := range tk {
			lch := colorx.RGBToLCH(token.RGB)
			fmt.Fprintf(&out, "%-30s /* %s · %s · oklch(%.1f%% %.3f %.0f) */\n", "  --"+token.Key+": "+token.Hex+";", safeComment(token.Name), safeComment(token.Job), lch.L*100, lch.C, lch.H)
		}
		out.WriteString("}\n")
	case "godot":
		fmt.Fprintf(&out, "## %s — Godot 4 colour pack\n## generated by Scene Palette\n## review: %s\nextends Resource\nclass_name ColorPlate\n\n", name, review)
		for _, token := range tk {
			fmt.Fprintf(&out, "const %s := Color(\"%s\")  # %s — %s\n", strings.ToUpper(token.Key), strings.ToLower(token.Hex), safeComment(token.Name), safeComment(token.Job))
		}
		out.WriteString("\nconst TOKENS := {\n")
		for _, token := range tk {
			fmt.Fprintf(&out, "\t\"%s\": %s,\n", token.Key, strings.ToUpper(token.Key))
		}
		out.WriteString("}\n\nfunc apply_to_theme(theme: Theme) -> void:\n\ttheme.set_color(\"font_color\", \"Label\", INK)\n\ttheme.set_color(\"font_color\", \"Button\", INK)\n\ttheme.set_color(\"font_color\", \"RichTextLabel\", INK)\n\tvar surface := StyleBoxFlat.new()\n\tsurface.bg_color = PANEL\n\tsurface.set_corner_radius_all(6)\n\ttheme.set_stylebox(\"panel\", \"PanelContainer\", surface)\n\tvar btn := StyleBoxFlat.new()\n\tbtn.bg_color = ATTENTION\n\tbtn.set_corner_radius_all(4)\n\ttheme.set_stylebox(\"normal\", \"Button\", btn)\n")
	case "gpl":
		fmt.Fprintf(&out, "GIMP Palette\nName: %s\nColumns: 8\n# Review: %s\n#\n", name, review)
		for _, token := range tk {
			slug := strings.Trim(tokenSlug.ReplaceAllString(strings.ToLower(token.Name), "_"), "_")
			if slug == "" {
				slug = "token"
			}
			fmt.Fprintf(&out, "%3d %3d %3d\t%s_%s\n", token.RGB.R, token.RGB.G, token.RGB.B, token.Key, slug)
		}
	case "hex":
		fmt.Fprintf(&out, "# Review: %s\n", review)
		for index, token := range tk {
			if index > 0 {
				out.WriteByte('\n')
			}
			fmt.Fprintf(&out, "%s  %s  (%s · %s)", token.Hex, safeComment(token.Name), token.Key, safeComment(token.Job))
		}
	case "json":
		var value json.RawMessage = data
		encoded, err := json.MarshalIndent(value, "", "  ")
		return string(encoded), err
	case "notes":
		return notes(data, document, tk, verified), nil
	default:
		return "", fmt.Errorf("unsupported bundle format %q", format)
	}
	return out.String(), nil
}

func safeComment(value string) string {
	value = strings.ReplaceAll(value, "*/", "*")
	value = strings.NewReplacer("\r", " ", "\n", " ").Replace(value)
	return strings.TrimSpace(value)
}

func reviewLabel(document palette.Document, verified palette.ReviewVerification) string {
	label := "proposed · not agent-eligible"
	if document.Review != nil && document.Review.Status == "edited" {
		label = "edited · not agent-eligible"
	}
	if verified.AgentEligible {
		scope := "legacy palette content only"
		if verified.Scope == palette.ReviewScopePaletteAndSourceIdentities {
			scope = "palette + source identities"
		}
		label = "human-sealed · agent-eligible · " + scope
		if document.Review.SealedAt != nil {
			label += " · " + *document.Review.SealedAt
		}
	}
	if n := verified.Assessment.AttentionCount; n > 0 {
		label += fmt.Sprintf(" · %d review note%s", n, plural(n))
	} else {
		label += " · review checks clear"
	}
	if n := len(verified.RecordedHistory); n > 0 {
		label += fmt.Sprintf(" · %d prior seal%s recorded", n, plural(n))
	}
	if verified.AgentEligible {
		label += " · " + verified.Computed.Algo + ":" + verified.Computed.Value
	}
	return safeComment(label)
}

func plural(n int) string {
	if n == 1 {
		return ""
	}
	return "s"
}

func notes(data []byte, document palette.Document, tk []exportToken, verified palette.ReviewVerification) string {
	var metadata struct {
		Sources []struct {
			File, Path       string
			Retained         *bool
			Natural, Working []int
			Hash             *palette.Hash
		} `json:"sources"`
		Notes []string `json:"notes"`
	}
	_ = json.Unmarshal(data, &metadata)
	var out strings.Builder
	fmt.Fprintf(&out, "# %s\n\n%s plate\n\nGenerated by %s %s (extraction v%d, schema %d).\n\n## Human review\n\n- %s\n", safeMarkdown(document.Name), document.Polarity, safeMarkdown(document.Generator.Name), safeMarkdown(document.Generator.Version), *document.Generator.Extraction, document.Schema, reviewLabel(document, verified))
	if !verified.AgentEligible {
		out.WriteString("- A person must review and seal this plate before an agent consumes it.\n")
	}
	if decision := verified.RecordedDecision; decision != nil && decision.Baseline {
		fmt.Fprintf(&out, "- Decision: %d changed item%s, %d changed field%s.\n", decision.ChangeCount, plural(decision.ChangeCount), decision.FieldCount, plural(decision.FieldCount))
	} else {
		out.WriteString("- Decision: no proposal baseline recorded.\n")
	}
	if len(verified.RecordedHistory) > 0 {
		out.WriteString("\n## Prior human seals\n\nRecorded audit provenance only; earlier palette content is not retained and prior fingerprints cannot be reverified.\n\n")
		for _, history := range verified.RecordedHistory {
			stamp, reason := "time not recorded", "reason not recorded"
			if history.SealedAt != nil {
				stamp = *history.SealedAt
			}
			if history.InvalidatedBy != nil {
				reason = *history.InvalidatedBy
			}
			fmt.Fprintf(&out, "- %s — superseded: %s\n", safeMarkdown(stamp), safeMarkdown(reason))
		}
	}
	out.WriteString("\n## Review focus\n\n")
	for _, check := range verified.Assessment.Checks {
		fmt.Fprintf(&out, "- **%s — %s:** %s\n", safeMarkdown(check.Label), check.Status, safeMarkdown(check.Detail))
	}
	out.WriteString("\nAttention is advisory; the human seal records the final judgment.\n\n## Sources\n\n")
	if len(metadata.Sources) == 0 {
		out.WriteString("- none recorded\n")
	}
	for _, source := range metadata.Sources {
		fmt.Fprintf(&out, "- `%s` — %s", safeMarkdown(source.Path), safeMarkdown(source.File))
		if source.Hash != nil {
			fmt.Fprintf(&out, ", %s:%s", safeMarkdown(source.Hash.Algo), safeMarkdown(source.Hash.Value))
		}
		if source.Retained != nil && !*source.Retained {
			out.WriteString(", source bytes not retained")
		}
		out.WriteByte('\n')
	}
	out.WriteString("\n## Plate\n\n| key | hex | name | job | origin |\n| --- | --- | --- | --- | --- |\n")
	for _, token := range tk {
		var origin struct {
			Kind string `json:"kind"`
		}
		_ = json.Unmarshal(token.Origin, &origin)
		fmt.Fprintf(&out, "| `%s` | %s | %s | %s | %s |\n", token.Key, token.Hex, safeMarkdown(token.Name), safeMarkdown(token.Job), safeMarkdown(origin.Kind))
	}
	out.WriteString("\n## Notes\n\n")
	if len(metadata.Notes) == 0 {
		out.WriteString("- none\n")
	}
	for _, note := range metadata.Notes {
		fmt.Fprintf(&out, "- %s\n", safeMarkdown(note))
	}
	out.WriteString("\n---\nThis folder is the authority. `index.json` elsewhere is a cache and can be rebuilt from it.\n")
	return out.String()
}

func safeMarkdown(value string) string {
	return strings.NewReplacer("|", `\|`, "`", "'", "<", "&lt;", ">", "&gt;").Replace(safeComment(value))
}
